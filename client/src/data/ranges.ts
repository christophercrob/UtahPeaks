export type RangeRing = Array<[number, number]>; // [lat, lng] pairs
export type RangePolygonGroup = RangeRing[]; // exterior first, followed by any holes

export interface MountainRange {
  range: string;
  peak: string;
  elevation: string;
  elevationFt: number;
  lat: number;
  lon: number;
  trailhead: string;
  trailheadLat: number;
  trailheadLon: number;
  gain: string;
  color: string;
  polygon: RangeRing; // Primary exterior ring; preserved for legacy consumers.
  polygonGroups?: RangePolygonGroup[]; // Multipart geometry and holes for spatially clipped ranges.
  boundaryType?: "line"; // Defaults to a filled polygon; KML LineStrings use "line".
  // Personal hiking journal fields
  summited?: boolean;
  summitDate?: string;           // e.g. "July 11, 2026"
  hikeNote?: string;             // short personal note about the hike
  accessNotes?: string[];        // route, access, and safety advisories for the hike journal
  trailheadPhoto?: { url: string; caption?: string };
  summitPhoto?: { url: string; caption?: string };
  attempted?: boolean;           // true if attempted but not yet summited
  attemptDate?: string;          // date of the attempt
  attemptNote?: string;          // note about the attempt
  extraPhotos?: Array<{ url: string; caption?: string }>;  // additional gallery photos
  videoUrl?: string;             // link to a video (Google Photos, YouTube, etc.)
}

